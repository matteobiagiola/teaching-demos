import torch
from torch import nn
import torch.nn.functional as F


class Net(nn.Module):
    """Convolutional neural network for the MNIST dataset.

    The network has two convolutional layers (conv1 and conv2) and two fully
    connected layers (fc1 and fc2). A ReLU function follows conv1, conv2 and
    fc1.
    """

    def __init__(self) -> None:
        super().__init__()
        self.conv1 = nn.Conv2d(1, 32, 3, 1)
        self.conv2 = nn.Conv2d(32, 64, 3, 1)
        self.dropout1 = nn.Dropout(0.25)
        self.dropout2 = nn.Dropout(0.5)
        self.flatten = nn.Flatten(1)
        self.fc1 = nn.Linear(9216, 128)
        self.fc2 = nn.Linear(128, 10)

    def forward(self, x: torch.Tensor) -> torch.Tensor:
        """Computes the output of the network.

        Args:
            x: Batch of images with shape [batch, 1, 28, 28].

        Returns:
            The log-probability of each class, with shape [batch, 10].
        """
        x = self.conv1(x)
        x = F.relu(x)
        x = self.conv2(x)
        x = F.relu(x)
        x = F.max_pool2d(x, 2)
        x = self.dropout1(x)
        x = self.flatten(x)
        x = self.fc1(x)
        x = F.relu(x)
        x = self.dropout2(x)
        x = self.fc2(x)
        output = F.log_softmax(x, dim=1)
        return output
